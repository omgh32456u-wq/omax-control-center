-- Omax Control Center metadata extension.
-- Existing code hashes, subscriptions, redemption RPC, and status/duration constraints are preserved.
begin;

alter table public.omax_activation_codes
  add column if not exists assigned_name text,
  add column if not exists notes text,
  add column if not exists tier text not null default 'standard';

alter table public.omax_subscriptions
  add column if not exists tier text not null default 'standard';

-- Ensure audit events can be inserted without clients inventing primary keys.
-- Preserve an existing sequence/default/identity if the table already has one.
do $audit_id$
declare
  v_default text;
  v_identity text;
begin
  select column_default, is_identity
    into v_default, v_identity
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'omax_audit_logs'
    and column_name = 'id';

  if v_default is null and coalesce(v_identity, 'NO') = 'NO' then
    alter table public.omax_audit_logs
      alter column id add generated by default as identity;
    perform setval(
      pg_get_serial_sequence('public.omax_audit_logs', 'id'),
      coalesce((select max(id) from public.omax_audit_logs), 0) + 1,
      false
    );
  end if;
end;
$audit_id$;

do $constraints$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'omax_activation_codes_tier_check'
      and conrelid = 'public.omax_activation_codes'::regclass
  ) then
    alter table public.omax_activation_codes
      add constraint omax_activation_codes_tier_check
      check (tier in ('standard', 'premium'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'omax_subscriptions_tier_check'
      and conrelid = 'public.omax_subscriptions'::regclass
  ) then
    alter table public.omax_subscriptions
      add constraint omax_subscriptions_tier_check
      check (tier in ('standard', 'premium'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'omax_activation_codes_assigned_name_length'
      and conrelid = 'public.omax_activation_codes'::regclass
  ) then
    alter table public.omax_activation_codes
      add constraint omax_activation_codes_assigned_name_length
      check (assigned_name is null or char_length(assigned_name) <= 120);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'omax_activation_codes_notes_length'
      and conrelid = 'public.omax_activation_codes'::regclass
  ) then
    alter table public.omax_activation_codes
      add constraint omax_activation_codes_notes_length
      check (notes is null or char_length(notes) <= 500);
  end if;
end;
$constraints$;

-- Preserve the existing redemption RPC implementation. It already writes
-- activation_code_id into the subscription; this trigger copies that code's tier.
create or replace function public.omax_set_subscription_tier_from_code()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_tier text;
begin
  if new.activation_code_id is not null then
    select c.tier into v_tier
    from public.omax_activation_codes as c
    where c.id = new.activation_code_id;

    if v_tier is not null then
      new.tier := v_tier;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists omax_subscriptions_set_tier_from_code
  on public.omax_subscriptions;

create trigger omax_subscriptions_set_tier_from_code
before insert or update of activation_code_id
on public.omax_subscriptions
for each row
execute function public.omax_set_subscription_tier_from_code();

-- The existing redemption RPC extends an existing subscription without replacing
-- activation_code_id. Once it marks the new code as redeemed, propagate that code's
-- tier to the user's current active subscription as well.
create or replace function public.omax_apply_redeemed_code_tier()
returns trigger
language plpgsql
security definer
set search_path = ''
as $omax$
begin
  if new.redeemed_by is not null
     and (old.redeemed_by is distinct from new.redeemed_by) then
    update public.omax_subscriptions as s
    set tier = new.tier,
        updated_at = now()
    where s.id = (
      select candidate.id
      from public.omax_subscriptions as candidate
      where candidate.user_id = new.redeemed_by
        and candidate.status = 'active'
        and candidate.expires_at > now()
      order by candidate.expires_at desc, candidate.created_at desc
      limit 1
    );
  end if;
  return new;
end;
$omax$;

drop trigger if exists omax_activation_codes_apply_redeemed_tier
  on public.omax_activation_codes;

create trigger omax_activation_codes_apply_redeemed_tier
after update of redeemed_by
on public.omax_activation_codes
for each row
execute function public.omax_apply_redeemed_code_tier();

commit;
